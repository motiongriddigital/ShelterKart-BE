#!/usr/bin/env python3
"""ShelterKart brand builder. Reads brand/tokens.json (the only place colours, fonts and the brand marks are defined) and writes:

  brand/dist/tokens.css          CSS custom properties and @font-face rules, fonts by relative path (for the website)
  brand/dist/tokens.inline.css   the same, with the fonts embedded as data: URIs (for self-contained pages and PDFs)
  brand/dist/icon.svg            the icon on paper (navy page, gold fold)      brand/dist/icon-on-navy.svg  for dark surfaces
  brand/dist/app-icon.svg        the icon on a navy tile, for browser tabs and home screens
  brand/dist/lockup-light.svg    icon + name + tagline, on paper               brand/dist/lockup-dark.svg   on navy
  brand/dist/wordmark-light.svg  icon + name, no tagline (small places)        brand/dist/wordmark-dark.svg
  brand/dist/share-card.png      1200 x 630, the preview image for shared links
  brand/dist/favicon-32.png, apple-touch-icon.png (180), icon-192.png, icon-512.png

and copies the favicons to icons/ and the share card to the site root, where the pages already point.
It stops if any text colour pair in tokens.json fails WCAG AA (4.5:1), so a colour that cannot be read never ships.
    python3 brand/build_brand.py
"""
import asyncio, base64, json, os, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DIST = os.path.join(HERE, 'dist'); os.makedirs(DIST, exist_ok=True)
T = json.load(open(os.path.join(HERE, 'tokens.json'), encoding='utf-8'))
C = {k: v['hex'] for k, v in T['colors'].items()}

# ---------------------------------------------------------------- contrast: a colour that cannot be read never ships
def _lum(h):
    h = h.lstrip('#'); r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
def contrast(a, b):
    la, lb = _lum(a), _lum(b); hi, lo = max(la, lb), min(la, lb); return (hi + 0.05) / (lo + 0.05)
failed = [(fg, bg, round(contrast(C[fg], C[bg]), 2)) for fg, bg in T['contrast'] if contrast(C[fg], C[bg]) < 4.5]
assert not failed, f'text colours below 4.5:1 contrast: {failed}'

# ---------------------------------------------------------------- CSS
b64 = lambda p: base64.b64encode(open(os.path.join(HERE, p), 'rb').read()).decode()
D, X = T['fonts']['display'], T['fonts']['text']
TEXT = f"'{X['family']}',{T['fonts']['textFallback']}"; DISP = f"'{D['family']}',{T['fonts']['displayFallback']}"
kebab = lambda s: ''.join('-' + c.lower() if c.isupper() else c for c in s)
def css(inline):
    src = (lambda p, fmt: f"url(data:font/{'woff2' if fmt == 'woff2' else 'ttf'};base64,{b64(p)}) format('{fmt}')") if inline else (lambda p, fmt: f"url('{p}') format('{fmt}')")
    faces = [f"@font-face{{font-family:'{D['family']}';src:{src(D['file'], D['format'])};font-weight:{D['weight']};font-style:normal;font-display:swap}}"]
    faces += [f"@font-face{{font-family:'{X['family']}';src:{src(p, X['format'])};font-weight:{w};font-style:normal;font-display:swap}}" for w, p in X['files'].items()]
    vars_ = ''.join(f'--sk-{kebab(k)}:{v};' for k, v in C.items())
    vars_ += f"--sk-font-text:{TEXT};--sk-font-display:{DISP};"
    vars_ += ''.join(f'--sk-radius-{k}:{v}px;' for k, v in T['radius'].items())
    vars_ += f"--sk-measure:{T['type']['measureCh']}ch;--sk-line:{T['type']['lineHeight']};--sk-fade:{T['motion']['fadeMs']}ms;--sk-tick:{T['motion']['tickMs']}ms;"
    motion = '@media (prefers-reduced-motion:reduce){*,*::before,*::after{animation:none!important;transition:none!important;scroll-behavior:auto!important}}'
    return '/* Generated by brand/build_brand.py from brand/tokens.json. Do not edit. */\n' + '\n'.join(faces) + f'\n:root{{{vars_}}}\n{motion}\n'
open(os.path.join(DIST, 'tokens.css'), 'w', encoding='utf-8').write(css(False).replace("url('fonts/", "url('../fonts/"))
open(os.path.join(DIST, 'tokens.inline.css'), 'w', encoding='utf-8').write(css(True))

# ---------------------------------------------------------------- the icon: a closed page, level base, folded corner in gold
def icon_paths(line, fold):
    w = T['stroke']['icon']
    return (f'<path d="M15 6 H40 L50 16 V58 H15 Z" fill="none" stroke="{line}" stroke-width="{w}" stroke-linejoin="round"/>'
            f'<path d="M40 6 V16 H50" fill="{fold}" stroke="{fold}" stroke-width="2.4" stroke-linejoin="round"/>'
            f'<path d="M23 30 H42 M23 40 H42" stroke="{line}" stroke-width="2.6" stroke-linecap="round"/>')
svg = lambda vb, body, w=None, h=None: f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"' + (f' width="{w}" height="{h}"' if w else '') + f' role="img" aria-label="{T["name"]}">{body}</svg>'
ICON = svg('0 0 64 64', icon_paths(C['navy'], C['gold']), 64, 64)
ICON_DARK = svg('0 0 64 64', icon_paths(C['cream'], C['gold']), 64, 64)
APP = svg('0 0 64 64', f'<rect width="64" height="64" rx="12" fill="{C["navy"]}"/><g transform="translate(6.5,5) scale(.8)">{icon_paths(C["cream"], C["gold"])}</g>', 64, 64)
FACE = f"<defs><style>@font-face{{font-family:'{D['family']}';src:url(data:font/woff2;base64,{b64(D['file'])}) format('woff2');font-weight:600}}</style></defs>"
def lockup(line, name_fill, tag_fill, with_tag=True):
    w, h = (560, 120) if with_tag else (440, 76)
    body = FACE + f'<g transform="translate(0,{6 if with_tag else 6})">{icon_paths(line, C["gold"])}</g>'
    body += f'<text x="90" y="{50 if with_tag else 48}" font-family="{D["family"]},Georgia,serif" font-weight="600" font-size="46" letter-spacing="-0.6" fill="{name_fill}">{T["name"]}</text>'
    if with_tag: body += f'<text x="91" y="86" font-family="{D["family"]},Georgia,serif" font-weight="600" font-size="20" letter-spacing="0.2" fill="{tag_fill}">{T["tagline"]}</text>'
    return svg(f'0 0 {w} {h}', body, w, h)
files = {'icon.svg': ICON, 'icon-on-navy.svg': ICON_DARK, 'app-icon.svg': APP,
         'lockup-light.svg': lockup(C['navy'], C['navy'], C['slate']), 'lockup-dark.svg': lockup(C['cream'], C['cream'], '#B9C4D4'),
         'wordmark-light.svg': lockup(C['navy'], C['navy'], None, False), 'wordmark-dark.svg': lockup(C['cream'], C['cream'], None, False)}
for n, s in files.items(): open(os.path.join(DIST, n), 'w', encoding='utf-8').write(s)

# ---------------------------------------------------------------- rendered images: favicons and the share card
SHARE = f'''<!doctype html><html><head><meta charset="utf-8"><style>{css(True)}
html,body{{margin:0}} .card{{width:1200px;height:630px;background:{C['navy']};color:{C['cream']};position:relative;overflow:hidden;font-family:var(--sk-font-text)}}
.frame{{position:absolute;inset:34px;border:1px solid rgba(211,162,69,.45);border-radius:6px}}
.icon{{position:absolute;left:110px;top:170px;width:150px;height:150px}}
.name{{position:absolute;left:310px;top:168px;font-family:var(--sk-font-display);font-weight:600;font-size:104px;letter-spacing:-1.5px;line-height:1}}
.rule{{position:absolute;left:314px;top:306px;width:120px;height:3px;background:{C['gold']}}}
.tag{{position:absolute;left:312px;top:336px;font-family:var(--sk-font-display);font-weight:600;font-size:46px;line-height:1.2}}
.foot{{position:absolute;left:112px;bottom:78px;font-size:22px;letter-spacing:.14em;text-transform:uppercase;color:{C['gold']};font-weight:700}}
</style></head><body><div class="card"><div class="frame"></div><img class="icon" src="data:image/svg+xml;base64,{base64.b64encode(ICON_DARK.encode()).decode()}" alt="">
<div class="name">{T['name']}</div><div class="rule"></div><div class="tag">{T['tagline']}</div><div class="foot">{T['domain']}</div></div></body></html>'''
async def render():
    from playwright.async_api import async_playwright
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={'width': 1200, 'height': 630}); await pg.set_content(SHARE); await pg.evaluate('document.fonts.ready'); await pg.wait_for_timeout(200)
        await pg.locator('.card').screenshot(path=os.path.join(DIST, 'share-card.png'))
        # the app icon: rendered once at 512 px from the icon element itself, then scaled down, so every size has the same shape
        pg2 = await b.new_page(viewport={'width': 600, 'height': 600}, device_scale_factor=1)
        await pg2.set_content('<html><body style="margin:0;background:transparent">' + APP.replace('width="64" height="64"', 'width="512" height="512"', 1) + '</body></html>')   # count 1: the outer frame only, as the tile inside is also 64 x 64
        await pg2.locator('svg').screenshot(path=os.path.join(DIST, 'icon-512.png'), omit_background=True); await pg2.close()
        await b.close()
asyncio.run(render())
from PIL import Image
big = Image.open(os.path.join(DIST, 'icon-512.png')).convert('RGBA')
assert big.size == (512, 512), f'the icon rendered at {big.size}, expected 512 x 512'
for name, size in (('favicon-32.png', 32), ('apple-touch-icon.png', 180), ('icon-192.png', 192)): big.resize((size, size), Image.LANCZOS).save(os.path.join(DIST, name))

# ---------------------------------------------------------------- copy to where each surface already points
os.makedirs(os.path.join(ROOT, 'icons'), exist_ok=True)
for n in ('favicon-32.png', 'apple-touch-icon.png', 'icon-192.png', 'icon-512.png'): shutil.copy2(os.path.join(DIST, n), os.path.join(ROOT, 'icons', n))
shutil.copy2(os.path.join(DIST, 'share-card.png'), os.path.join(ROOT, 'share-card.png'))
print(f"brand built: {len(C)} colours, every text pair at or above 4.5:1 (lowest {min(round(contrast(C[a], C[b]), 2) for a, b in T['contrast'])}); "
      f"icon, lockups, favicons and share card written; favicons copied to icons/, share card to the site root")
